<h2>Qué datos tratamos y para qué</h2>
<ul>
  <li>
    <strong>Lista de espera:</strong> tu email, la fecha en que diste tu consentimiento y la fecha en
    que lo confirmaste. Solo para avisarte cuando abramos Soleva. Base legal: tu consentimiento.
  </li>
  <li>
    <strong>Cuenta:</strong> tu email, para mandarte el código con el que entras, y una sesión (identificador
    y fecha de caducidad) para que no tengas que entrar cada vez. No guardamos tu dirección IP ni tu navegador
    con la sesión. Base legal: el contrato que aceptas al crear tu cuenta.
  </li>
  <li>
    <strong>Protección contra abusos:</strong> cuando pides un código o lo introduces, usamos tu dirección
    IP para limitar los intentos. Se guarda junto a un contador y se borra automáticamente a partir de
    los 10 minutos. Base legal: nuestro interés legítimo en proteger el servicio y tu cuenta.
  </li>
  <li>
    <strong>Lo que apuntes en la app</strong> (cuentas, saldos, reglas): solo para darte el servicio.
    Base legal: el contrato.
  </li>
</ul>
<p>
  No vendemos tus datos, no mostramos anuncios y no usamos analítica de terceros que te rastree.
