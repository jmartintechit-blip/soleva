<h2>Qué es Soleva</h2>
<p>
  Soleva es una herramienta de planificación personal: apuntas tus cuentas y cómo entra y sale tu
  dinero, y te enseña una estimación de dónde estarás. No mueve dinero, no se conecta a tu banco ni
  a tu bróker, no es un asesor financiero y no recomienda productos de inversión.
</p>
<p>
  Las proyecciones y la calculadora son estimaciones basadas en los supuestos que se indican en cada
  caso. No son asesoramiento ni garantizan ningún resultado.
