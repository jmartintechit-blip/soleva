<h2>Qué es Soleva</h2>
<p>
  Soleva es una herramienta de planificación personal: apuntas tus cuentas y cómo entra y sale tu
  dinero, y te enseña una estimación de dónde estarás. No mueve dinero y no se conecta a tu banco ni
  a tu bróker.
</p>
<p>
  Soleva no presta servicios de inversión ni asesoramiento en materia de inversión en el sentido de
  la Ley 6/2023, de los Mercados de Valores y de los Servicios de Inversión. No te hace
  recomendaciones personalizadas sobre productos o instrumentos financieros concretos, no evalúa tu
  perfil de inversor, no recibe ni transmite órdenes y no custodia dinero ni valores.
</p>
<p>
  Las cuentas, los importes y las rentabilidades los introduces tú. Las proyecciones son cálculos
  matemáticos sobre esos supuestos, con fines informativos. Antes de invertir, consulta con un
  profesional autorizado por la CNMV.
</p>

